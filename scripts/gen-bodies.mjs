#!/usr/bin/env node
/**
 * Generates src/gtoc13Bodies.js from the official GTOC13 ephemeris files.
 *
 * Usage: node scripts/gen-bodies.mjs <dir-with-gtoc13_{planets,asteroids,comets}.csv>
 *
 * The official CSVs are Latin-1 with CRLF line endings. Values are copied
 * verbatim (as written in the CSV) so the validator uses exactly the published
 * elements.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/gen-bodies.mjs <dir with gtoc13_*.csv>');
  process.exit(1);
}

function readCsv(name) {
  const buf = readFileSync(join(dir, name));
  const sha = createHash('sha256').update(buf).digest('hex');
  const rows = buf.toString('latin1').split(/\r?\n/)
    .map(l => l.trim())
    .filter(l => l && !l.startsWith('#'))
    .map(l => l.split(',').map(s => s.trim()));
  return { name, sha, rows };
}

const planets = readCsv('gtoc13_planets.csv');
const asteroids = readCsv('gtoc13_asteroids.csv');
const comets = readCsv('gtoc13_comets.csv');

const lines = [];
// planets.csv: ID, Name, GM, Radius, a, e, i, RAAN, argp, M0, weight
for (const r of planets.rows) {
  const [id, name, gm, radius, a, e, i, raan, argp, M0, w] = r;
  lines.push(`  [${id}, ${JSON.stringify(name)}, ${gm}, ${radius}, ${a}, ${e}, ${i}, ${raan}, ${argp}, ${M0}, ${w}],`);
}
// asteroids.csv / comets.csv: ID, a, e, i, RAAN, argp, M0, weight
for (const [src, prefix] of [[asteroids, 'Asteroid'], [comets, 'Comet']]) {
  for (const r of src.rows) {
    const [id, a, e, i, raan, argp, M0, w] = r;
    lines.push(`  [${id}, "${prefix} ${id}", 0, 0, ${a}, ${e}, ${i}, ${raan}, ${argp}, ${M0}, ${w}],`);
  }
}

const out = `/**
 * GTOC13 body ephemeris table — AUTO-GENERATED by scripts/gen-bodies.mjs. Do not edit.
 *
 * Source: official GTOC13 ephemeris files (JPL, 2025):
 *   ${planets.name}    sha256 ${planets.sha}
 *   ${asteroids.name}  sha256 ${asteroids.sha}
 *   ${comets.name}     sha256 ${comets.sha}
 *
 * Units: GM km^3/s^2, radius km, a km, angles deg, M0 = mean anomaly at t = 0.
 * Yandi (1000), asteroids and comets are massless (GM = 0, radius = 0).
 */

// [id, name, gm, radius, a, e, i, raan, argp, M0, weight]
const RAW = [
${lines.join('\n')}
];

export const GTOC13_BODIES = Object.freeze(Object.fromEntries(RAW.map(
  ([id, name, gm, radius, a, e, i, raan, argp, M0, weight]) =>
    [id, Object.freeze({ id, name, gm, radius, a, e, i, raan, argp, M0, weight })]
)));
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'gtoc13Bodies.js');
writeFileSync(target, out);
console.log(`wrote ${target}: ${planets.rows.length} planets/dwarf, ${asteroids.rows.length} asteroids, ${comets.rows.length} comets`);
